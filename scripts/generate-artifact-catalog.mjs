import { execFileSync } from "node:child_process";
import { lstat, readFile, realpath, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { projects, routableProjects } from "../src/lib/projects.ts";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const output = path.join(root, "src/lib/artifact-catalog.generated.mjs");
// Only reviewed, tracked public files enter the viewer. Never include local uploads,
// untracked files, symlinks, or arbitrary files just because their extension matches.
const files = execFileSync("git", ["ls-files", "-z", "--", "public/case-studies"], { cwd: root, encoding: "utf8" })
  .split("\0").filter((file) => /\.(png|jpe?g|svg|pdf|json|csv|md|mmd|txt)$/i.test(file)).sort();
for (const file of files) {
  const absolute = path.join(root, file);
  if (!(await lstat(absolute)).isFile() || await realpath(absolute) !== absolute) throw new Error(`Not a regular artifact: ${file}`);
}
const paths = files.map((file) => file.slice("public".length));
const identities = Object.fromEntries([...new Set(paths.map((file) => file.split("/")[2]))].map((directory) => {
  const project = projects.find((candidate) => candidate.slug === directory);
  if (!project) throw new Error(`Missing project metadata: ${directory}`);
  const route = directory === "analytics-tandem" ? "/#archive"
    : routableProjects.includes(project) ? `/${project.track}/${project.slug}` : "/";
  return [directory, { title: project.title, route }];
}));
const content = `// Generated by scripts/generate-artifact-catalog.mjs; review and commit catalog changes.\nexport const artifactPaths = ${JSON.stringify(paths, null, 2)};\n\nexport const artifactProjects = ${JSON.stringify(identities, null, 2)};\n`;
if (process.argv.includes("--check")) {
  if (await readFile(output, "utf8") !== content) throw new Error("Artifact catalog is stale. Run npm run generate:artifacts and review the diff.");
} else await writeFile(output, content);
console.log(`Artifact catalog: ${paths.length} files, ${Object.keys(identities).length} project directories.`);
